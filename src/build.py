import os,shutil,hashlib,datetime
BASE=os.path.dirname(os.path.abspath(__file__))
def p(*parts): return os.path.join(BASE,*parts)

src=open(p('app.src.html')).read()
D='https://frontswatch.com'
desc='Interactive daily map of the war in Yemen from 2014 to today: who holds each governorate, strikes, fighting, decisions and outlook, each with sources.'
i=src.index('</style>')+len('</style>')
head=f'''<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<meta name="description" content="{desc}">
<link rel="canonical" href="{D}/">
<link rel="icon" href="/favicon.svg" type="image/svg+xml">
<link rel="manifest" href="/manifest.webmanifest">
<link rel="apple-touch-icon" href="/apple-touch-icon.png">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-title" content="Frontswatch">
<meta property="og:type" content="website">
<meta property="og:title" content="Frontswatch: Yemen conflict map">
<meta property="og:description" content="{desc}">
<meta property="og:url" content="{D}/">
<meta property="og:image" content="{D}/og.png">
<meta property="og:image:width" content="1200">
<meta property="og:image:height" content="630">
<meta property="og:image:alt" content="Frontswatch (راصد): daily map of the war in Yemen">
<meta property="og:site_name" content="Frontswatch · راصد">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:image" content="{D}/og.png">
<meta name="theme-color" content="#0c1216">
<script type="application/ld+json">{{"@context":"https://schema.org","@type":"WebSite","name":"Frontswatch","alternateName":"راصد","url":"{D}/","description":"{desc}"}}</script>
'''
site=head+src[:i]+'\n</head>\n<body>'+src[i:]+"\n<script>if('serviceWorker' in navigator&&location.protocol==='https:')addEventListener('load',()=>navigator.serviceWorker.register('/sw.js').catch(()=>{}))</script>\n</body>\n</html>\n"

out=p('..','site') if os.path.basename(BASE)=='src' else p('site')
shutil.rmtree(out,ignore_errors=True); os.makedirs(out)

for _f in ('data.js','geo.js','ar.js'):
    _h=hashlib.md5(open(p(_f),'rb').read()).hexdigest()[:8]
    site=site.replace(f'<script src="{_f}"></script>',f'<script src="{_f}?v={_h}"></script>')
open(out+'/index.html','w').write(site)
open(out+'/_headers','w').write('/data.js\n  Cache-Control: public, max-age=31536000, immutable\n/geo.js\n  Cache-Control: public, max-age=31536000, immutable\n/ar.js\n  Cache-Control: public, max-age=31536000, immutable\n/\n  Cache-Control: public, max-age=0, must-revalidate\n/index.html\n  Cache-Control: public, max-age=0, must-revalidate\n/sw.js\n  Cache-Control: no-cache\n')
for f in ('data.js','geo.js','ar.js'): shutil.copy(p(f),out+'/'+f)
for f in os.listdir(p('pwa')): shutil.copy(p('pwa',f),out+'/'+f)
open(out+'/robots.txt','w').write(f'User-agent: *\nAllow: /\nSitemap: {D}/sitemap.xml\n')
today=datetime.date.today().isoformat()
open(out+'/sitemap.xml','w').write(f'<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n  <url><loc>{D}/</loc><lastmod>{today}</lastmod></url>\n</urlset>\n')
open(out+'/README.txt','w').write('''FRONTSWATCH - SITE FOLDER (generated by build.py, do not edit by hand)

This folder is built automatically from the source files one level up
(app.src.html, data.js, geo.js, ar.js, pwa/). Run build.py again after
editing those to regenerate it.
''')

artifact_dir=p('..','artifact') if os.path.basename(BASE)=='src' else p('artifact')
os.makedirs(artifact_dir,exist_ok=True)
open(artifact_dir+'/index.html','w').write(src)
print('built ->',out)
